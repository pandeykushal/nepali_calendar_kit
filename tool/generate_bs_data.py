#!/usr/bin/env python3
"""Generate lib/src/engine/bs_calendar_data.dart from an Excel/CSV table.

Expected sheet layout (first row = headers), one row per BS year:

    BS Year | Baisakh | Jestha | Ashadh | Shrawan | Bhadra | Ashwin |
            | Kartik  | Mangsir| Poush  | Magh    | Falgun | Chaitra

Every month value must be an integer 29..32. Years must be contiguous.

Usage:
    python tool/generate_bs_data.py DATA.xlsx \
        --anchor-bs 2000-01-01 --anchor-ad 1943-04-14 \
        --out bs_verified_snippet.dart   # then splice into the engine file

The anchor is ONE verified BS=AD pair that must fall inside the table.
"""
import argparse
import sys
from datetime import date

try:
    import openpyxl  # noqa: F401
    import pandas as pd
except ImportError:
    sys.exit("Please: pip install pandas openpyxl")


def load_rows(path):
    if path.lower().endswith((".csv", ".tsv")):
        sep = "\t" if path.lower().endswith(".tsv") else ","
        df = pd.read_csv(path, sep=sep)
    else:
        df = pd.read_excel(path)
    df = df.dropna(how="all")
    # First column = year; next 12 = months (by position, header names ignored).
    if df.shape[1] < 13:
        sys.exit(f"Expected >=13 columns (year + 12 months), got {df.shape[1]}.")
    table = {}
    for _, row in df.iterrows():
        vals = row.tolist()
        try:
            year = int(vals[0])
            months = [int(v) for v in vals[1:13]]
        except (TypeError, ValueError):
            continue  # skip non-data rows
        table[year] = months
    return table


def validate(table):
    problems = []
    years = sorted(table)
    for y in range(years[0], years[-1] + 1):
        if y not in table:
            problems.append(f"Missing year {y} (table must be contiguous).")
            continue
        m = table[y]
        if len(m) != 12:
            problems.append(f"Year {y}: {len(m)} months, expected 12.")
        for i, d in enumerate(m):
            if not (29 <= d <= 32):
                problems.append(f"Year {y} month {i+1} = {d} (expected 29-32).")
    return problems


def emit(table, anchor_bs, anchor_ad, out_path):
    # Emits ONLY the verified map + anchor constants as a snippet. The
    # BsCalendarData class (with the verified/experimental toggle) is
    # hand-maintained in lib/src/engine/bs_calendar_data.dart — splice the
    # generated map/anchors in, do not overwrite the whole file.
    years = sorted(table)
    lines = [
        "// GENERATED by tool/generate_bs_data.py — splice into bs_calendar_data.dart.",
        "// Replaces kBsMonthDataVerified + the anchor constants only.",
        "",
        "/// Verified month-length table, keyed by BS year (always active).",
        "const Map<int, List<int>> kBsMonthDataVerified = <int, List<int>>{",
    ]
    for y in years:
        lines.append(f"  {y}: <int>[{', '.join(str(d) for d in table[y])}],")
    lines.append("};")
    lines.append("")
    by, bm, bd = anchor_bs
    ay, am, ad = anchor_ad
    for name, val in [
        ("kAnchorBsYear", by), ("kAnchorBsMonth", bm), ("kAnchorBsDay", bd),
        ("kAnchorAdYear", ay), ("kAnchorAdMonth", am), ("kAnchorAdDay", ad),
    ]:
        lines.append("/// Conversion anchor component.")
        lines.append(f"const int {name} = {val};")
    lines.append("")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {out_path}: {len(years)} years "
          f"({years[0]}–{years[-1]}).")


def parse_ymd(s):
    parts = s.split("-")
    if len(parts) != 3:
        raise argparse.ArgumentTypeError(f"Expected YYYY-MM-DD, got {s}")
    return tuple(int(p) for p in parts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("data", help="Path to .xlsx / .csv table")
    ap.add_argument("--anchor-bs", type=parse_ymd, default=(2000, 1, 1))
    ap.add_argument("--anchor-ad", type=parse_ymd, default=(1943, 4, 14))
    ap.add_argument("--out", default="bs_verified_snippet.dart",
                    help="Snippet file to splice into bs_calendar_data.dart "
                         "(does NOT overwrite the engine file).")
    args = ap.parse_args()

    table = load_rows(args.data)
    if not table:
        sys.exit("No data rows parsed — check the sheet layout.")
    problems = validate(table)
    if problems:
        print("DATA PROBLEMS (fix before shipping):", file=sys.stderr)
        for p in problems[:50]:
            print("  -", p, file=sys.stderr)
        sys.exit(1)

    by = args.anchor_bs
    ay, am, ad = args.anchor_ad
    # Sanity: anchor AD must be a real date and anchor BS year must be present.
    date(ay, am, ad)
    if by[0] not in table:
        sys.exit(f"Anchor BS year {by[0]} not in table.")

    emit(table, by, args.anchor_ad, args.out)


if __name__ == "__main__":
    main()
