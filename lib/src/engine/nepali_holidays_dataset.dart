/// Candidate list for [year] (2081 or 2082), else empty.
List<NepaliHoliday> candidateHolidaysForYear(int year) {
  switch (year) {
    case 2081:
      return kCandidateHolidays2081;
    case 2082:
      return kCandidateHolidays2082;
    default:
      return const <NepaliHoliday>[];
  }
}
