/// Conversion anchor: 1 Baisakh 1970 BS = 13 April 1913 AD (verified).
/// Anchor BS year.
const int kAnchorBsYear = 1970;
/// Anchor BS month.
const int kAnchorBsMonth = 1;
/// Anchor BS day.
const int kAnchorBsDay = 1;
/// Anchor AD year.
const int kAnchorAdYear = 1913;
/// Anchor AD month.
const int kAnchorAdMonth = 4;
/// Anchor AD day.
const int kAnchorAdDay = 13;

/// Access to the active BS month-length table.
///
/// By default only the verified range (1969-2250) is active. Enable the
/// experimental pre-1969 range (1898-1968, unverified) with
/// [includeExperimental] - e.g. in a family-tree app that needs ancestors.
abstract final class BsCalendarData {
  static bool _includeExperimental = false;
  static Map<int, List<int>>? _cache;
  static int _min = 0;
  static int _max = 0;

  /// Whether the unverified pre-1969 experimental range is merged in.
  static bool get includeExperimental => _includeExperimental;

  /// Enables/disables the experimental pre-1969 range. Set once at startup
  /// (before converting), since it changes [minYear].
  static set includeExperimental(bool value) {
    if (value != _includeExperimental) {
      _includeExperimental = value;
      _cache = null;
    }
  }

  static void _rebuild() {
    final m = <int, List<int>>{
      if (_includeExperimental) ...kBsMonthDataExperimental,
      ...kBsMonthDataVerified,
    };
    final keys = m.keys.toList()..sort();
    _cache = m;
    _min = keys.first;
    _max = keys.last;
  }

  /// The active table (verified, plus experimental when enabled).
  static Map<int, List<int>> get data {
    if (_cache == null) _rebuild();
    return _cache!;
  }

  /// Lowest active BS year.
  static int get minYear {
    if (_cache == null) _rebuild();
    return _min;
  }

  /// Highest active BS year.
  static int get maxYear {
    if (_cache == null) _rebuild();
    return _max;
  }

  /// Whether [year] is in the active table.
  static bool hasYear(int year) => data.containsKey(year);

  /// Days in the 1-based [month] of BS [year]. Throws if out of range.
  static int daysInMonth(int year, int month) {
    final months = data[year];
    if (months == null) {
      throw ArgumentError.value(year, 'year',
          'BS year is outside the active table ($minYear-$maxYear). '
          'For pre-1969, set BsCalendarData.includeExperimental = true.');
    }
    if (month < 1 || month > 12) {
      throw ArgumentError.value(month, 'month', 'Month must be 1-12');
    }
    return months[month - 1];
  }

  /// Total days in BS [year].
  static int daysInYear(int year) {
    final months = data[year];
    if (months == null) {
      throw ArgumentError.value(year, 'year',
          'BS year is outside the active table ($minYear-$maxYear).');
    }
    var sum = 0;
    for (final d in months) {
      sum += d;
    }
    return sum;
  }

  /// Structural integrity check of the active table; empty list means sound.
  static List<String> validate() {
    final problems = <String>[];
    final years = data.keys.toList()..sort();
    for (var y = years.first; y <= years.last; y++) {
      final months = data[y];
      if (months == null) {
        problems.add('Missing year $y (table must be contiguous).');
        continue;
      }
      if (months.length != 12) {
        problems.add('Year $y has ${months.length} months, expected 12.');
      }
    }
    if (!hasYear(kAnchorBsYear)) {
      problems.add('Anchor year $kAnchorBsYear is not in the table.');
    }
    return problems;
  }
}
